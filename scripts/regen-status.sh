# regen-status.sh — regenerate specs/NNN-feature/STATUS.md from ticket
# frontmatter. The board is derived, never hand-edited; this script is the
# single source for it.
#
# Why: with 107+ tickets in 001-tor-route alone and more features coming,
# asking an agent or a human to grep tasks.md for "what's runnable / in
# flight / blocked" is fragile. STATUS.md is the answer — a single page that
# mirrors the frontmatter state of truth.
#
# Precedent: infochat's docs/plan/m1/STATUS.md + scripts/regen-status.py,
# adapted to stargate's frontmatter (privacy_critical, constitution_refs)
# and feature-scoped rather than milestone-scoped.
#
# Usage:
#   scripts/regen-status.sh                       # active feature (.specify/feature.json)
#   scripts/regen-status.sh specs/001-tor-route   # explicit feature
#   scripts/regen-status.sh --all                 # every specs/* with a tickets/ dir

set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

ALL=0
EXPLICIT=""
for arg in "$@"; do
  case "$arg" in
    --all) ALL=1 ;;
    --*) echo "regen-status: unknown flag: $arg" >&2; exit 2 ;;
    *) EXPLICIT="$arg" ;;
  esac
done

# Determine feature directory list.
if [ "$ALL" = "1" ]; then
  FEATURE_DIRS=(specs/*/)
elif [ -n "$EXPLICIT" ]; then
  FEATURE_DIRS=("$EXPLICIT")
else
  DEFAULT="$(python3 -c '
import json
try:
    cfg = json.load(open(".specify/feature.json"))
    print(cfg.get("feature_directory", "specs/001-tor-route"))
except Exception:
    print("specs/001-tor-route")
' 2>/dev/null || echo "specs/001-tor-route")"
  FEATURE_DIRS=("$DEFAULT")
fi

for FEATURE_DIR in "${FEATURE_DIRS[@]}"; do
  [ -d "$FEATURE_DIR/tickets" ] || continue
  TICKETS_DIR="$FEATURE_DIR/tickets"
  STATUS_FILE="$FEATURE_DIR/STATUS.md"

  python3 - "$TICKETS_DIR" "$STATUS_FILE" <<'PY'
import glob, os, re, sys
from datetime import datetime, date

tickets_dir, status_file = sys.argv[1], sys.argv[2]

# --- targeted frontmatter extraction (mirrors lint-ticket.py / next-task.sh) --
def parse(path):
    txt = open(path).read()
    m = re.match(r'^---\n(.*?)\n---\n', txt, re.DOTALL)
    if not m: return {}
    out = {}
    lines = m.group(1).splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        mm = re.match(r'^([a-z_]+):\s*(.*)$', line)
        if not mm:
            i += 1; continue
        key = mm.group(1)
        rest = re.sub(r'\s+#.*$', '', mm.group(2)).rstrip()
        if rest.startswith('['):
            inner = rest.strip('[]').strip()
            out[key] = [] if not inner else [v.strip().strip("'\"") for v in inner.split(',')]
        elif rest == '':
            vals = []
            j = i + 1
            while j < len(lines) and re.match(r'^\s+-\s+', lines[j]):
                vals.append(re.sub(r'^\s+-\s+', '', lines[j]).strip().strip("'\""))
                j += 1
            out[key] = vals if vals else ''
        else:
            out[key] = rest.strip("'\"")
        i += 1
    return out

# --- collect -----------------------------------------------------------------
tickets = []
for p in sorted(glob.glob(f'{tickets_dir}/T*-*.md')):
    fm = parse(p)
    if not fm.get('id'): continue
    tickets.append({**fm, '_path': p, '_title': fm.get('title', '')})

# --- id sort key -------------------------------------------------------------
def sort_key(t):
    tid = t.get('id', '')
    m = re.match(r'^T0*(\d+)([a-z]?)$', tid)
    if not m: return (99999, '')
    return (int(m.group(1)), m.group(2))

tickets.sort(key=sort_key)

# --- classify ----------------------------------------------------------------
buckets = {'pending': [], 'in-progress': [], 'in-review': [],
           'escalated': [], 'done': [], 'deferred': []}
for t in tickets:
    s = t.get('status', 'pending')
    buckets.setdefault(s, []).append(t)

# Build id→status map for blocked_by resolution.
id_status = {t.get('id'): t.get('status', 'pending') for t in tickets}

def runnable(t):
    if t.get('status') != 'pending': return False
    deps = t.get('blocked_by', [])
    if isinstance(deps, str): deps = [deps] if deps else []
    return all(id_status.get(d) == 'done' for d in deps)

runnable_tickets = [t for t in tickets if runnable(t)]

# --- render ------------------------------------------------------------------
today = date.today().isoformat()
out = []
out.append(f"# STATUS — {os.path.basename(os.path.dirname(tickets_dir))}")
out.append("")
out.append("> **Auto-generated by `scripts/regen-status.sh`.** Do not hand-edit.")
out.append("> Source of truth is the frontmatter of the files under `tickets/`.")
out.append("> If this file disagrees with frontmatter, frontmatter wins; re-run")
out.append("> `scripts/regen-status.sh` to regenerate.")
out.append("")
out.append(f"**Last updated:** {today}")
out.append("")
out.append("---")
out.append("")
out.append("## Summary")
out.append("")
out.append("| Status | Count |")
out.append("|---|---|")
order = ['pending', 'in-progress', 'in-review', 'escalated', 'done', 'deferred']
for s in order:
    out.append(f"| {s} | {len(buckets.get(s, []))} |")
out.append(f"| **total** | **{len(tickets)}** |")
out.append("")
out.append("---")
out.append("")
out.append("## Runnable now")
out.append("")
out.append(f"Tickets where `status: pending` AND every `blocked_by` is `done`.")
out.append("")
if runnable_tickets:
    out.append("| ID | Title | Phase | Priv? | Parallel? |")
    out.append("|---|---|---|---|---|")
    for t in runnable_tickets:
        priv = "✓" if t.get('privacy_critical') == 'true' else ""
        par = "✓" if t.get('parallel') == 'true' else ""
        title = t.get('_title', '')[:60]
        out.append(f"| {t.get('id')} | {title} | {t.get('phase', '-')} | {priv} | {par} |")
else:
    out.append("_(none — every pending ticket has unsatisfied `blocked_by`, or no pending tickets.)_")
out.append("")
out.append("---")
out.append("")
out.append("## In flight")
out.append("")
inflight = [t for t in tickets if t.get('status') in ('in-progress', 'in-review', 'escalated')]
if inflight:
    out.append("| ID | Title | Status | Privacy | Phase |")
    out.append("|---|---|---|---|---|")
    for t in inflight:
        priv = "✓" if t.get('privacy_critical') == 'true' else ""
        out.append(f"| {t.get('id')} | {t.get('_title', '')[:60]} | {t.get('status')} | {priv} | {t.get('phase', '-')} |")
else:
    out.append("_(nothing in flight)_")
out.append("")
out.append("---")
out.append("")
out.append("## Deferred")
out.append("")
deferred = [t for t in tickets if t.get('status') == 'deferred']
if deferred:
    out.append("| ID | Title | Reason | Blocked on |")
    out.append("|---|---|---|---|")
    for t in deferred:
        reason = t.get('deferred_reason', '-') or '-'
        on = t.get('deferred_on', '-') or '-'
        out.append(f"| {t.get('id')} | {t.get('_title', '')[:60]} | {reason} | {on} |")
else:
    out.append("_(none deferred)_")
out.append("")
out.append("---")
out.append("")
out.append("## Done")
out.append("")
done = buckets.get('done', [])
out.append(f"_{len(done)} ticket(s) done._")
out.append("")
if done:
    # Compact one-line-per-ticket list, not a wide table.
    for t in done:
        out.append(f"- {t.get('id')} — {t.get('_title', '')[:70]}")
out.append("")

# Write atomically (write to temp + rename so a half-write never appears).
tmp = status_file + '.tmp'
open(tmp, 'w').write('\n'.join(out))
os.replace(tmp, status_file)

# Summary on stdout — one line, contract for callers.
counts = {s: len(buckets.get(s, [])) for s in order}
print(f"regen-status: {status_file}: "
      + " ".join(f"{s}={counts[s]}" for s in order)
      + f" total={len(tickets)} runnable={len(runnable_tickets)}")
PY
done
